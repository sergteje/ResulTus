using System.Text;

namespace ResulTus.SourceGenerators;

/// <summary>
/// Writes one <see cref="FactoryShape"/> out as a complete, self-contained C# file.
/// </summary>
internal static class FactoryEmitter
{
    private const string ReturnType = "global::ResulTus.Error";

    private const string AutoGeneratedHeader = "// <auto-generated/>";

    /// <summary>
    /// Renders the shape as a file and gives it its hint name.
    /// </summary>
    /// <param name="shape">The factory to render.</param>
    /// <returns>The rendered file.</returns>
    internal static FactoryModel Emit(FactoryShape shape)
    {
        var builder = new StringBuilder();

        builder.AppendLine(AutoGeneratedHeader);
        builder.AppendLine("#nullable enable");
        builder.AppendLine();

        var depth = 0;

        if (shape.Namespace is not null)
        {
            builder.Append("namespace ").Append(shape.Namespace).AppendLine();
            builder.AppendLine("{");
            depth++;
        }

        foreach (var containingType in shape.ContainingTypes)
        {
            AppendIndent(builder, depth).AppendLine(containingType.Declaration);
            AppendIndent(builder, depth).AppendLine("{");
            depth++;
        }

        AppendIndent(builder, depth)
            .Append(shape.Accessibility)
            .Append("static partial ")
            .Append(ReturnType)
            .Append(' ')
            .Append(shape.MethodName)
            .Append('(')
            .Append(shape.Parameters)
            .AppendLine(")");

        AppendIndent(builder, depth + 1)
            .Append("=> ")
            .Append(ReturnType)
            .Append('.')
            .Append(shape.Type)
            .Append('(')
            .Append('"')
            .Append(Escape(shape.Code))
            .Append('"');

        if (shape.MessageTemplate is not null)
        {
            // The template is written verbatim inside an interpolated string: its braces are the
            // placeholders, so only the characters that would end the literal are escaped.
            builder.Append(", $\"").Append(Escape(shape.MessageTemplate)).Append('"');
        }

        builder.AppendLine(");");

        for (var index = shape.ContainingTypes.Length - 1; index >= 0; index--)
        {
            depth--;
            AppendIndent(builder, depth).AppendLine("}");
        }

        if (shape.Namespace is not null)
        {
            builder.AppendLine("}");
        }

        return new FactoryModel(BuildHintName(shape), builder.ToString());
    }

    /// <summary>
    /// Builds the hint name from the factory's identity.
    /// </summary>
    /// <remarks>
    /// The readable part is there so a generated file can be recognized in a diagnostic, and the
    /// hash is there because the readable part is not unique on its own: two overloads share a
    /// namespace, a type chain and a method name. Both halves are safe as a file name without
    /// further escaping, because every component is a C# identifier and the hash is hexadecimal.
    /// </remarks>
    /// <param name="shape">The factory to name.</param>
    /// <returns>A unique, filesystem-safe hint name.</returns>
    private static string BuildHintName(FactoryShape shape)
    {
        var identity = new StringBuilder();

        identity.Append(shape.Namespace ?? string.Empty).Append('.');

        foreach (var containingType in shape.ContainingTypes)
        {
            identity.Append(containingType.Name).Append('.');
        }

        identity.Append(shape.MethodName).Append('(').Append(shape.Parameters).Append(')');

        var readable = new StringBuilder();

        if (shape.Namespace is not null)
        {
            readable.Append(shape.Namespace).Append('.');
        }

        foreach (var containingType in shape.ContainingTypes)
        {
            readable.Append(containingType.Name).Append('.');
        }

        readable.Append(shape.MethodName);

        return readable.ToString()
            + "."
            + StableHash.Of(identity.ToString())
            + ".g.cs";
    }

    private static StringBuilder AppendIndent(StringBuilder builder, int depth)
        => builder.Append(' ', depth * 4);

    /// <summary>
    /// Escapes the two characters that would otherwise end or corrupt the emitted string literal.
    /// </summary>
    /// <param name="value">The text to escape.</param>
    /// <returns>The escaped text.</returns>
    private static string Escape(string value)
        => value.Replace("\\", "\\\\").Replace("\"", "\\\"");
}
